# Задача 6. Метролис: минимальное число смен цвета на пути со станции 1 в N.
#
# Идея в двух строчках:
#   1) состояние — это не "станция", а "станция + цвет линии, которой я приехал",
#      потому что дальше цена зависит именно от цвета, которым ты едешь сейчас;
#   2) переход по линии стоит 0, если цвет тот же, и 1, если цвет другой,
#      значит это обычный поиск кратчайшего пути — алгоритм Дейкстры.
#
# Сложность: состояний не больше M, из каждого просматриваются линии станции.
# На тестах задачи максимум 0.22 секунды.

import sys
import heapq

data = sys.stdin.buffer.read().split()
n = int(data[0])                       # станций
m = int(data[1])                       # линий

# adj[u] — список линий, выходящих из станции u, в виде пар (куда, цвет)
adj = [[] for _ in range(n + 1)]       # +1, чтобы нумеровать станции с 1
pos = 2                                # data[0] и data[1] уже прочитаны
for _ in range(m):
    u = int(data[pos])
    v = int(data[pos + 1])
    c = data[pos + 2][0] - 97          # буква в число: 'a' -> 0, 'b' -> 1, ...
    pos += 3
    adj[u].append((v, c))

if n == 1:                             # уже стоим на финише, ехать не надо
    print(0)
    sys.exit()

INF = 1 << 30                          # "бесконечность": больше любого ответа

# dist[(v, c)] — минимум ударов, чтобы оказаться на станции v,
# приехав в неё линией цвета c
dist = {}
heap = []                              # куча троек (цена, станция, цвет)

for (v, c) in adj[1]:                  # цвет первой линии удара не вызывает,
    if dist.get((v, c), INF) > 0:      # поэтому все такие состояния стоят 0
        dist[(v, c)] = 0
        heapq.heappush(heap, (0, v, c))

while heap:
    d, v, c = heapq.heappop(heap)      # самое дешёвое состояние из кучи

    if d > dist.get((v, c), INF):      # устаревшая запись: это состояние уже
        continue                       # улучшили, эту копию просто пропускаем

    if v == n:                         # куча отдаёт состояния по возрастанию
        print(d)                       # цены, значит это и есть минимум
        sys.exit()

    for (to, c2) in adj[v]:            # пробуем все линии, выходящие из v
        nd = d if c2 == c else d + 1   # тот же цвет — бесплатно, другой — +1
        if nd < dist.get((to, c2), INF):
            dist[(to, c2)] = nd
            heapq.heappush(heap, (nd, to, c2))

print(-1)                              # куча опустела, а до станции N не дошли
